#!/usr/bin/env node
// Offline one-time export of a local data/inventory.sqlite into a D1 import SQL
// file plus an R2 photo upload script. It never contacts Cloudflare.
import { existsSync, readFileSync, writeFileSync, mkdirSync, statSync, realpathSync } from 'node:fs';
import { dirname, resolve, relative, isAbsolute, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
import { MAX_PHOTO_BYTES, looksLikeImage, normalizeBatch } from '../lib/shared.js';

const R2_BUCKET = 'medicine-inventory-photos';
const uuidPattern = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const idPattern = /^[A-Za-z0-9-]{1,64}$/;
const mimeByExt = { '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp' };
const extByMime = { 'image/jpeg': '.jpg', 'image/png': '.png', 'image/webp': '.webp' };

const q = value => value === null || value === undefined ? 'NULL' : typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
const sh = value => `'${String(value).replaceAll("'", "'\\''")}'`;

function photoFor(row, dataDir) {
  if (!row.photo_path) return {};
  const abs = resolve(dataDir, row.photo_path);
  const rel = relative(resolve(dataDir), abs);
  if (!rel || rel.startsWith('..') || isAbsolute(rel)) return { warning: 'photo path is outside the data directory' };
  if (!existsSync(abs)) return { warning: 'photo file is missing' };
  const realRel = relative(realpathSync(dataDir), realpathSync(abs));
  if (realRel.startsWith('..') || isAbsolute(realRel)) return { warning: 'photo path is outside the data directory' };
  const mime = mimeByExt[extname(abs).toLowerCase()];
  if (!mime) return { warning: 'photo type is not JPEG, PNG or WebP' };
  const size = statSync(abs).size;
  if (!size || size > MAX_PHOTO_BYTES) return { warning: 'photo is empty or larger than 2 MB' };
  if (!looksLikeImage(readFileSync(abs), mime)) return { warning: 'photo content is not a valid image' };
  return { abs, mime, ext: extByMime[mime] };
}

export function buildExport({ shopId, dbPath, dataDir = dirname(dbPath) }) {
  if (!uuidPattern.test(String(shopId || ''))) throw new Error('--shop-id must be the Shop UUID (households.id).');
  if (!existsSync(dbPath)) throw new Error(`Local database not found: ${dbPath}`);
  const db = new DatabaseSync(dbPath, { readOnly: true });
  let rows;
  try { rows = db.prepare('SELECT * FROM batches ORDER BY created_at, id').all(); } finally { db.close(); }
  const summary = { total: rows.length, imported: 0, photos: 0, skippedDiscarded: 0, skippedEmpty: 0, invalid: [], warnings: [] };
  const statements = [];
  const uploads = [];
  for (const row of rows) {
    if (row.discarded_at) { summary.skippedDiscarded += 1; continue; }
    if (!idPattern.test(String(row.id))) { summary.invalid.push(`${row.id}: unsupported id`); continue; }
    if (row.quantity === 0) { summary.skippedEmpty += 1; continue; }
    let b;
    try { b = normalizeBatch(row, true); } catch { summary.invalid.push(`${row.id} (${row.name}): invalid medicine details`); continue; }
    if (typeof row.created_at !== 'string' || !row.created_at || typeof row.updated_at !== 'string' || !row.updated_at) {
      summary.invalid.push(`${row.id} (${row.name}): missing timestamps`); continue;
    }
    const photo = photoFor(row, dataDir);
    if (photo.warning) summary.warnings.push(`${row.id} (${row.name}): ${photo.warning}; imported without photo`);
    const key = photo.abs ? `photos/${row.id}${photo.ext}` : null;
    if (key) uploads.push({ key, file: photo.abs, mime: photo.mime });
    statements.push(
      `INSERT OR IGNORE INTO batches (id,household_id,name,strength,form,quantity,unit,expiry_date,location,notes,low_stock_threshold,photo_path,created_at,updated_at,revision) VALUES (${[row.id, shopId, b.name, b.strength, b.form, b.quantity, b.unit, b.expiry_date, b.location, b.notes, b.low_stock_threshold, key, row.created_at, row.updated_at, 1].map(q).join(',')});`,
      `INSERT INTO batch_changes (household_id,batch_id,revision,kind,created_at) SELECT ${q(shopId)},${q(row.id)},1,'upsert',${q(row.updated_at)} WHERE NOT EXISTS (SELECT 1 FROM batch_changes WHERE household_id=${q(shopId)} AND batch_id=${q(row.id)});`
    );
    summary.imported += 1;
  }
  summary.photos = uploads.length;
  const sql = [
    '-- Generated by tools/export-local-to-d1.js. Idempotent: re-running skips existing batches.',
    '-- Requires the target Shop to exist (foreign key on household_id). No secrets or push subscriptions.',
    ...statements, ''
  ].join('\n');
  const script = ['#!/bin/sh', '# Generated by tools/export-local-to-d1.js. Uploads packaging photos to R2 (overwrites same keys).', 'set -eu',
    ...uploads.map(u => `npx wrangler r2 object put ${sh(`${R2_BUCKET}/${u.key}`)} --remote --file ${sh(u.file)} --content-type ${sh(u.mime)}`), ''].join('\n');
  return { sql, script, summary };
}

export function formatSummary(s) {
  const lines = [`Local batches: ${s.total}`, `To import: ${s.imported} (${s.photos} with photos)`, `Skipped discarded: ${s.skippedDiscarded}`, `Skipped zero quantity: ${s.skippedEmpty}`, `Invalid (skipped): ${s.invalid.length}`];
  for (const x of s.invalid) lines.push(`  invalid: ${x}`);
  for (const x of s.warnings) lines.push(`  warning: ${x}`);
  return lines.join('\n');
}

function main(argv) {
  const opts = { db: 'data/inventory.sqlite', out: 'data/d1-import.sql', photosOut: null, dryRun: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--dry-run') opts.dryRun = true;
    else if (['--shop-id', '--db', '--out', '--photos-out'].includes(a)) {
      if (argv[i + 1] === undefined) throw new Error(`${a} needs a value.`);
      opts[a.slice(2).replace(/-(\w)/g, (_, c) => c.toUpperCase())] = argv[++i];
    } else throw new Error(`Unknown argument: ${a}`);
  }
  const dbPath = resolve(opts.db);
  const out = resolve(opts.out);
  const photosOut = resolve(opts.photosOut || out.replace(/\.sql$/, '') + '-photos.sh');
  const { sql, script, summary } = buildExport({ shopId: opts.shopId, dbPath });
  console.log(formatSummary(summary));
  if (opts.dryRun) { console.log('Dry run: no files written.'); return; }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, sql);
  writeFileSync(photosOut, script, { mode: 0o755 });
  console.log(`Wrote ${out}\nWrote ${photosOut}`);
}

